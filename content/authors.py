AUTHOR_KEYS = list(AUTHORS.keys())

def format_author_card(key: str) -> str:
    a = AUTHORS.get(key)
    if not a: return "Автор табылмады."
    return f"{a['emoji']} <b>{a['name']}</b> ({a.get('years', '')})\n\n{a['bio']}"

def format_author_full(key: str) -> str:
    a = AUTHORS.get(key)
    if not a: return "Автор табылмады."
    works = "\n".join(f"• {w}" for w in a.get('works', []))
    facts = "\n".join(f"✓ {f}" for f in a.get('facts', []))
    return f"{a['emoji']} <b>{a['name']}</b>\n\n📖 <b>Шығармалары:</b>\n{works}\n\n💡 <b>Бір қызық:</b>\n{facts}"

def format_infographic(key: str) -> str:
    a = AUTHORS.get(key)
    if not a: return "Автор табылмады."
    quotes = "\n\n".join(f"💬 \"{q}\"" for q in a.get('quotes', []))
    return f"🎨 <b>{a['name']} — Инфографика</b>\n\n{quotes}"
