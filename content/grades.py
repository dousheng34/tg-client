def get_topic_content(grade: int, topic_key: str) -> str:
    """Нақты тақырып мазмұнын қайтарады"""
    topics = get_grade_topics(grade)
    for t in topics:
        if t["key"] == topic_key:
            return t["content"]
    return "Мазмұн жоқ."


